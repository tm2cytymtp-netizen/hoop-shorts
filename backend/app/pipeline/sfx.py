def ensure_library() -> int:
    d = env.assets_dir / "sfx" / "generated"
    d.mkdir(parents=True, exist_ok=True)
    entries = []
    for name, (src, dur, flt) in RECIPES.items():
        out = d / f"{name}.wav"
        if not out.exists():
            args = ["-f", "lavfi", "-i", src]
            if flt:
                args += ["-af", flt]
            media.run(args + ["-t", str(dur), "-ar", "48000", "-ac", "2", str(out)])
        entries.append({"file": f"generated/{name}.wav", "title": name, "artist": "generated by this app",
                        "license": "Original synthesised sound (no third-party rights)", "commercial_use": True,
                        "tags": [name], "oneshot": True})
    (env.assets_dir / "sfx" / "generated.json").write_text(json.dumps(entries, indent=1))
    return len(entries)


